// Minimal generator for the JSON Schema subset currently used by this repository.
// Unsupported constructs fail explicitly; OpenAPI remains the source of truth.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const spec=JSON.parse(fs.readFileSync(path.join(root,'docs/contracts/openapi.json'),'utf8'));
const schemas=spec.components.schemas;
const goName=s=>s.split('_').map(p=>['id','ids','url','kph','csrf'].includes(p)?p.toUpperCase():p[0].toUpperCase()+p.slice(1)).join('');
function type(s){
 if(s.$ref)return s.$ref.split('/').pop();
 if(s.oneOf){const nonnull=s.oneOf.filter(x=>x.type!=='null');if(nonnull.length===1&&nonnull.length!==s.oneOf.length)return '*'+type(nonnull[0]);return 'json.RawMessage';}
 switch(s.type){
  case 'string':return 'string';case 'integer':return 'int';case 'number':return 'float64';case 'boolean':return 'bool';case 'null':return 'json.RawMessage';
  case 'array':return s.prefixItems?'json.RawMessage':'[]'+type(s.items);
  case 'object':return 'struct {\n'+Object.entries(s.properties||{}).map(([key,value])=>{let t=type(value);const optional=!(s.required||[]).includes(key);if(optional&&!t.startsWith('*'))t='*'+t;return goName(key)+' '+t+' `json:"'+key+(optional?',omitempty':'')+'"`';}).join('\n')+'\n}';
  default:throw Error('Unsupported schema '+JSON.stringify(s));
 }
}
let out='// Code generated by scripts/generate-go-contracts.cjs. DO NOT EDIT.\npackage contracts\n\nimport ("encoding/json"; "github.com/maksimkasimovhse/FamilyFriendlyRoutes/internal/routing")\n\n';
for(const [name,s]of Object.entries(schemas)){
 if(name==='Point'){out+='type Point = routing.Point\n';continue;}
 if(name==='Position'){out+='type Position = routing.Position\n';continue;}
 const value=type(s);out+='type '+name+(value==='json.RawMessage'?' = ':' ')+value+'\n\n';
}
fs.mkdirSync(path.join(root,'internal/contracts'),{recursive:true});fs.writeFileSync(path.join(root,'internal/contracts/models.gen.go'),out);
console.log('Generated '+Object.keys(schemas).length+' Go models.');
